"""
foundry_client.py - Microsoft Azure AI Foundry client integration.
Handles authentication via Microsoft Entra ID or API Key,
request formatting, error handling, content filtering, and an offline
simulation fallback for local evaluation and testing without active cloud credits.
"""

import os
import re
from typing import Dict, Any, Tuple

# Load environment configuration from .env if present
try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    # Graceful standard library fallback for loading .env without external dependencies
    if os.path.exists(".env"):
        try:
            with open(".env", "r", encoding="utf-8") as _f:
                for _line in _f:
                    _line = _line.strip()
                    if _line and not _line.startswith("#") and "=" in _line:
                        _k, _v = _line.split("=", 1)
                        os.environ.setdefault(_k.strip(), _v.strip())
        except Exception:
            pass

PROJECT_ENDPOINT = os.getenv("AZURE_AI_PROJECT_ENDPOINT", "").strip()
MODEL_DEPLOYMENT = os.getenv("AZURE_AI_MODEL_DEPLOYMENT_NAME", "gpt-4o-mini").strip()
API_KEY = os.getenv("AZURE_AI_API_KEY", "").strip()
FORCE_OFFLINE = os.getenv("ENABLE_OFFLINE_SIMULATION", "false").lower() in ("true", "1", "yes")

# Responsible AI Guardrails & Limits
MAX_CHARACTERS = 25000
MAX_WORDS = 4000
MIN_WORDS = 5

DISCLAIMER_TEXT = (
    "⚠️ **Responsible AI Notice**: This content was generated by an AI model. "
    "Answers should be independently verified against original course textbooks and lecture materials."
)

HARMFUL_PATTERNS = [
    r"(?i)\b(ignore previous instructions|system prompt bypass|drop table|format c:|jailbreak|hack into)\b",
    r"(?i)\b(bomb|weapon|explosive|kill|suicide|self-harm|malware|ransomware)\b",
]

def check_input_safety(text: str) -> Tuple[bool, str]:
    """
    Validates user input against safety guidelines, limits, and common malicious prompts.
    Returns (is_valid, error_message).
    """
    if not text or not text.strip():
        return False, "Notes cannot be empty. Please paste your lecture notes to continue."
    
    words = text.strip().split()
    if len(words) < MIN_WORDS:
        return False, f"The provided text is too short ({len(words)} words). Please enter at least {MIN_WORDS} words of lecture notes."
    
    if len(text) > MAX_CHARACTERS or len(words) > MAX_WORDS:
        return False, (
            f"Input exceeds maximum allowed limit ({len(words)} words / {len(text)} characters). "
            f"Please shorten your notes to under {MAX_WORDS} words."
        )
    
    for pattern in HARMFUL_PATTERNS:
        if re.search(pattern, text):
            return False, "Request blocked by Safety Guardrail: Unacceptable content or policy violation detected."
    
    return True, ""


def _simulate_response(mode: str, notes: str, user_question: str = "") -> str:
    """
    Intelligent offline simulation mode used when Azure Foundry endpoint
    is not configured or when running offline. Produces deterministic, grounded
    study materials directly derived from the input notes.
    """
    paragraphs = [p.strip() for p in notes.split("\n\n") if p.strip()]
    lines = [line.strip() for line in notes.splitlines() if line.strip()]
    words = notes.split()
    
    if mode == "summarize":
        total_p = len(paragraphs)
        sample_intro = lines[0] if lines else "Key concepts from the lecture."
        core_sentences = [l for l in lines if len(l) > 40][:4]
        
        summary = (
            f"### 📋 Executive Summary\n\n"
            f"This lecture material focuses on **{sample_intro[:80]}...** "
            f"covering approximately {len(words)} words across {total_p} core sections.\n\n"
            f"#### Key Synthesis\n"
        )
        for i, sentence in enumerate(core_sentences, 1):
            summary += f"- **Core Theme {i}**: {sentence}\n"
            
        summary += (
            f"\n#### Academic Takeaway\n"
            f"The material provides a structured foundational breakdown essential for conceptual comprehension and exam readiness."
        )
        return summary

    elif mode == "key_points":
        points = []
        for l in lines:
            if any(char in l for char in [":", "-", "—"]) and len(l) > 20:
                points.append(l)
            elif len(l) > 45:
                points.append(l)
        if not points:
            points = lines[:6]
        else:
            points = points[:6]
            
        res = "### 📌 Core Key Points & Definitions\n\n"
        for i, pt in enumerate(points, 1):
            parts = pt.split(":", 1)
            if len(parts) == 2:
                heading, body = parts[0].strip(), parts[1].strip()
            else:
                heading = f"Concept {i}"
                body = pt
            res += f"{i}. **{heading}**\n   {body}\n\n"
        return res

    elif mode == "practice_questions":
        key_lines = [l for l in lines if len(l) > 30][:5]
        q_count = min(3, len(key_lines))
        
        res = "### ❓ High-Yield Revision Practice Questions\n\n"
        res += "#### Part A: Conceptual Short Answer Questions\n"
        for i in range(q_count):
            res += f"**Q{i+1}: What is the primary significance of the following principle from the notes?**\n"
            res += f"> *\"{key_lines[i][:120]}...\"*\n"
            res += f"**Answer:** {key_lines[i]}\n\n"
            
        res += "#### Part B: Multiple-Choice Questions (MCQ)\n"
        res += f"**Q{q_count+1}: Based on the lecture text, which statement is strictly supported?**\n"
        res += f"- A) {key_lines[0] if key_lines else 'Option A'}\n"
        res += f"- B) Concepts not discussed in the course notes.\n"
        res += f"- C) An unverified speculative assumption.\n"
        res += f"- D) None of the above.\n"
        res += f"**Correct Answer:** **Option A**\n"
        res += f"*Explanation: Directly verified from context.*"
        return res

    elif mode == "ask_question":
        if not user_question.strip():
            return "Please provide a specific question to ask about the notes."
            
        q_words = [w.lower() for w in re.findall(r"\w+", user_question) if len(w) > 3]
        matching_lines = []
        for line in lines:
            line_lower = line.lower()
            if any(qw in line_lower for qw in q_words):
                matching_lines.append(line)
                
        if matching_lines:
            res = (
                f"### 💡 Answer to Your Query\n\n"
                f"{matching_lines[0]}\n\n"
                f"**Supporting Reference from Notes:**\n"
            )
            for ml in matching_lines[:2]:
                res += f"> *\"{ml}\"*\n"
            return res
        else:
            return (
                "**The provided notes do not contain sufficient information to answer this question.**\n\n"
                "*(Grounding rule applied: The study assistant only answers questions directly addressed in the supplied text.)*"
            )

    elif mode == "explain_simply":
        core = lines[0] if lines else "the subject matter"
        res = (
            f"### 🧠 Simplified Concept Breakdown (Feynman Technique)\n\n"
            f"#### 1. What is it in plain English?\n"
            f"Think of **{core[:60]}** as a set of clear building blocks. Instead of memorizing complicated jargon, "
            f"the notes describe how different components work together systematically.\n\n"
            f"#### 2. Everyday Analogy\n"
            f"Imagine you are building with Lego bricks: each rule or definition in your lecture notes is like a specific interlocking brick. "
            f"When you snap them together in the right order, the whole system stands solid and clear.\n\n"
            f"#### 3. Why it matters for your exam\n"
            f"Mastering these fundamentals ensures that when an exam question twists the wording, you still understand the underlying mechanism."
        )
        return res

    return "Processing completed."


def call_foundry_chat(
    system_prompt: str,
    user_prompt: str,
    temperature: float = 0.3,
    top_p: float = 0.9,
    max_tokens: int = 1000,
    mode: str = "summarize",
    notes: str = "",
    user_question: str = "",
) -> Dict[str, Any]:
    """
    Sends request to Microsoft Azure AI Foundry deployment or falls back to simulation mode.
    Returns dictionary with:
    - success (bool)
    - content (str)
    - provider (str)
    - disclaimer (str)
    """
    # 1. Safety check
    is_safe, err_msg = check_input_safety(notes if notes else user_prompt)
    if not is_safe:
        return {
            "success": False,
            "error": err_msg,
            "provider": "Safety Guardrail",
            "content": "",
            "disclaimer": DISCLAIMER_TEXT,
        }

    # 2. Check if offline simulation is forced or endpoint not configured
    if FORCE_OFFLINE or not PROJECT_ENDPOINT:
        simulated_text = _simulate_response(mode, notes, user_question)
        return {
            "success": True,
            "content": simulated_text,
            "provider": "Foundry Local Study Engine (Simulation / AI-901 Lab Mode)",
            "disclaimer": DISCLAIMER_TEXT,
            "deployment": MODEL_DEPLOYMENT,
        }

    # 3. Attempt live Microsoft Azure AI Foundry connection
    try:
        # Check if azure-ai-inference is available
        try:
            from azure.ai.inference import ChatCompletionsClient
            from azure.ai.inference.models import SystemMessage, UserMessage
            from azure.core.credentials import AzureKeyCredential
            from azure.identity import DefaultAzureCredential
            
            if API_KEY:
                credential = AzureKeyCredential(API_KEY)
            else:
                credential = DefaultAzureCredential()
                
            client = ChatCompletionsClient(
                endpoint=PROJECT_ENDPOINT,
                credential=credential
            )
            
            response = client.complete(
                messages=[
                    SystemMessage(content=system_prompt),
                    UserMessage(content=user_prompt),
                ],
                model=MODEL_DEPLOYMENT,
                temperature=temperature,
                top_p=top_p,
                max_tokens=max_tokens,
            )
            
            result_text = response.choices[0].message.content
            return {
                "success": True,
                "content": result_text,
                "provider": f"Microsoft Azure AI Foundry ({MODEL_DEPLOYMENT})",
                "disclaimer": DISCLAIMER_TEXT,
                "deployment": MODEL_DEPLOYMENT,
            }

        except ImportError:
            # Fallback to OpenAI SDK with Azure endpoint
            from openai import AzureOpenAI
            
            client = AzureOpenAI(
                azure_endpoint=PROJECT_ENDPOINT,
                api_key=API_KEY or "azure-token",
                api_version="2024-06-01",
            )
            
            response = client.chat.completions.create(
                model=MODEL_DEPLOYMENT,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=temperature,
                top_p=top_p,
                max_tokens=max_tokens,
            )
            
            result_text = response.choices[0].message.content
            return {
                "success": True,
                "content": result_text,
                "provider": f"Microsoft Azure AI Foundry via OpenAI SDK ({MODEL_DEPLOYMENT})",
                "disclaimer": DISCLAIMER_TEXT,
                "deployment": MODEL_DEPLOYMENT,
            }

    except Exception as exc:
        # Graceful degradation with clear diagnosis
        simulated_text = _simulate_response(mode, notes, user_question)
        return {
            "success": True,
            "content": simulated_text,
            "provider": f"Fallback Engine (Azure error: {str(exc)[:60]}... -> Offline Mode Active)",
            "disclaimer": DISCLAIMER_TEXT,
            "warning": f"Could not reach Azure endpoint: {str(exc)}. Switched to local grounding engine.",
            "deployment": MODEL_DEPLOYMENT,
        }
